import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const pkgPath = path.join(rootDir, 'node_modules', '@yowasp', 'clang', 'package.json');
if (!fs.existsSync(pkgPath)) {
  console.error("Error: @yowasp/clang is not installed.");
  process.exit(1);
}

const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
const version = pkg.version;
console.log(`Preparing toolchain for @yowasp/clang v${version}...`);

const genDir = path.join(rootDir, 'node_modules', '@yowasp', 'clang', 'gen');
const outDir = path.join(rootDir, 'public', 'toolchain', version);

fs.mkdirSync(outDir, { recursive: true });

const targetFiles = [
  'llvm-resources.tar',
  'llvm.core.wasm',
  'llvm.core2.wasm',
  'llvm.core3.wasm',
  'llvm.core4.wasm'
];

const collectFiles = (dir, prefix = '') => {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  return entries.flatMap(entry => {
    const relativePath = path.posix.join(prefix, entry.name);
    const absolutePath = path.join(dir, entry.name);
    return entry.isDirectory()
      ? collectFiles(absolutePath, relativePath)
      : [{ name: `extras/${relativePath}`, path: absolutePath }];
  });
};

const filesToPackage = [
  ...targetFiles.map(file => ({ name: file, path: path.join(genDir, file) })),
  ...collectFiles(path.join(rootDir, 'toolchain-extras'))
];

const manifestFiles = [];
let totalRawSize = 0;
let totalGzipSize = 0;

for (const { name: file, path: filePath } of filesToPackage) {
  if (!fs.existsSync(filePath)) {
    console.error(`Error: Missing file ${filePath}`);
    process.exit(1);
  }

  const rawBuffer = fs.readFileSync(filePath);
  const rawSize = rawBuffer.length;
  totalRawSize += rawSize;

  const hash = crypto.createHash('sha256').update(rawBuffer).digest('hex');

  console.log(`Gzipping ${file} (${(rawSize / 1024 / 1024).toFixed(2)} MB)...`);
  const gzippedBuffer = zlib.gzipSync(rawBuffer, { level: 9 });
  const gzipSize = gzippedBuffer.length;
  totalGzipSize += gzipSize;

  // Avoid a final .gz suffix: Vite treats that suffix as an HTTP gzip
  // Content-Encoding and browsers transparently decompress the response.
  // The client already runs DecompressionStream('gzip'), so that behavior
  // makes the cached-toolchain download fail on the development server.
  const outGzFile = `${file}.gz.bin`;
  const outGzPath = path.join(outDir, outGzFile);
  fs.mkdirSync(path.dirname(outGzPath), { recursive: true });
  // Remove artifacts generated by older script versions so builds don't ship
  // duplicate, server-auto-decompressed copies of the toolchain.
  fs.rmSync(path.join(outDir, `${file}.gz`), { force: true });
  fs.writeFileSync(outGzPath, gzippedBuffer);

  manifestFiles.push({
    name: file,
    gzFileName: outGzFile,
    rawSize,
    gzipSize,
    sha256: hash
  });

  console.log(`  -> ${outGzFile}: ${(gzipSize / 1024 / 1024).toFixed(2)} MB (saved ${((1 - gzipSize / rawSize) * 100).toFixed(1)}%)`);
}

const manifest = {
  version,
  totalRawSize,
  totalGzipSize,
  files: manifestFiles
};

const manifestPath = path.join(outDir, 'manifest.json');
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
console.log(`Manifest written to ${manifestPath}`);

// Write a root latest.json in public/toolchain/
const latestPath = path.join(rootDir, 'public', 'toolchain', 'latest.json');
fs.writeFileSync(latestPath, JSON.stringify({
  version,
  manifestPath: `toolchain/${version}/manifest.json`
}, null, 2));

console.log(`Toolchain preparation complete! Total raw: ${(totalRawSize / 1024 / 1024).toFixed(2)} MB, Total gzip: ${(totalGzipSize / 1024 / 1024).toFixed(2)} MB`);
